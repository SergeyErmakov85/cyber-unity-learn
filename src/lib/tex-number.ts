/**
 * Число для подстановки в формулу KaTeX.
 *
 * По правилам пособия (модуль «Код», п. 3.5) в формулах десятичный
 * разделитель — запятая, `0{,}9`, а точка остаётся только в коде и его
 * выводе. Фигурные скобки вокруг запятой убирают лишний пробел, который
 * TeX ставит после знака препинания.
 *
 *   texNum(0.9)        → "0{,}9"
 *   texNum(3.14159, 3) → "3{,}142"
 */
export function texNum(x: number, digits?: number): string {
  const s = digits === undefined ? String(x) : x.toFixed(digits);
  return s.replace(".", "{,}");
}
