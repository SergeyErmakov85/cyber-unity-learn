import type { EnfTone } from "@/lib/enf-roles";

/**
 * Запись словаря символов: одна строка таблицы «Символы: от формулы к коду»
 * и содержимое всплывающего пояснения по клику на символ.
 *
 * Текстовые поля понимают мини-разметку: `$...$` — формула KaTeX с макросами
 * ролей, обратные кавычки — код.
 */
export interface SymbolEntry {
  /** Запись символа без макроса роли: `\gamma`, `\hat{A}_t`, `Q`. */
  tex: string;
  /** Роль символа в формулах страницы (ENF-COLOR-010). */
  role: EnfTone;
  /** Короткое имя: «коэффициент дисконтирования». */
  name: string;
  /** Подробное объяснение: что это за величина и откуда берётся. */
  meaning: string;
  /** Что символ делает в формулах страницы. */
  inFormula?: string;
  /** Как символ записан в коде страницы: имя переменной, выражение, ключ конфига. */
  code?: string | string[];
  /** Тип, форма массива, где задаётся, ловушки перевода. */
  codeNote?: string;
  /**
   * Код взят из общего словаря, а не со страницы: так символ обычно пишут
   * в PyTorch/ML-Agents, но в листингах этой страницы его нет.
   */
  codeTypical?: boolean;
  /** Другие записи того же символа на странице: `\epsilon` для `\varepsilon`. */
  aliases?: string[];
}

/**
 * Служебный символ, который узнаётся по глифу, а не по макросу:
 * знаки операций, скобки, `\max`, `\sum`, `\mathbb{E}`, индексы.
 */
export interface GlyphEntry {
  /** Как глиф выглядит в отрендеренной формуле: «∑», «max», «←». */
  glyphs: string[];
  /** Класс KaTeX, в котором глиф встречается; без него — любой. */
  kinds?: Array<"mop" | "mbin" | "mrel" | "mopen" | "mclose" | "mpunct" | "mord" | "mathbb" | "mathcal" | "mathnormal" | "mathrm">;
  /** Только в индексе/степени, только в основной строке или везде. */
  where?: "script" | "main" | "any";
  /** TeX для крупного показа в пояснении. */
  tex: string;
  name: string;
  meaning: string;
  inFormula?: string;
  code?: string | string[];
  codeNote?: string;
}
