import type { EnfRoleOrNeutral } from "@/lib/enf-symbols";

/**
 * Одна строка словаря символов. Из таких строк собраны:
 *  - глобальный словарь сайта (`glossary.ts`) — карточка по клику на любой странице;
 *  - таблицы «Символы страницы: от формулы к коду» (`pages/*.ts`) — там, где на
 *    странице есть и формулы, и код; эти же строки карточка берёт в первую
 *    очередь, поэтому таблица и карточка не расходятся.
 *
 * В текстовых полях допустима строчная математика в `$...$` и код в `` `...` ``.
 */
export interface SymbolEntry {
  /** TeX символа ровно так, как он стоит внутри ролевого макроса: "\\gamma", "\\hat{A}", "Q". */
  tex: string;
  /** Роль по ENF; "neutral" — индексы, счётчики, множества, служебные операторы. */
  role: EnfRoleOrNeutral;
  /** Короткое название: «Коэффициент дисконтирования». */
  name: string;
  /** Что это такое — одно-три предложения. */
  meaning: string;
  /** Какую работу символ делает в формулах. */
  inFormula?: string;
  /** Как символ записан в Python-коде: `gamma`, `Q[s, a]`, `log_probs`. */
  code?: string;
  /** Тип и форма в коде: `float`, `torch.Tensor (B,)`. */
  codeType?: string;
  /** Замечание о переводе в код: ловушка, сдвиг индексов, где берётся значение. */
  codeNote?: string;
}

/** Таблица символов одной страницы. */
export interface PageSymbols {
  /** Уникальный id: по нему таблица регистрируется для карточек. */
  id: string;
  /** Подзаголовок таблицы: о каком коде речь. */
  caption?: string;
  symbols: SymbolEntry[];
}
